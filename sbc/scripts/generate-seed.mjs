// Generates supabase/migrations/0002_seed_content.sql from the real PROGS / PAGES in index.html,
// so the database starts with exactly what the original website shows.
// Run: node scripts/generate-seed.mjs        (safe to re-run; it only rewrites the .sql file)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(root, 'index.html'), 'utf8');

export function readSource() {
  const m = /(?:let|const) PROGS=/.exec(html);
  const b = html.indexOf('\nconst PAGES=');
  if (!m || b < 0) throw new Error('Could not find PROGS in index.html');
  const progs = new Function('return ' + html.slice(m.index + m[0].length, b).trim().replace(/;$/, ''))();
  return progs;
}

const slugs = ['school-supplies', 'disability-rehabilitation', 'sunshine-sports', 'care-for-the-elderly',
  'mothers-infants', 'food-dry-rations', 'water-building', 'toilets-sanitation'];
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";

if (import.meta.url === 'file://' + process.argv[1]) {
  const progs = readSource();
  let out = `-- GENERATED by scripts/generate-seed.mjs from index.html. Do not edit by hand.
-- Idempotent: running it again never duplicates a programme and never touches
-- anything an editor has changed (a programme's photos are only written the moment
-- the programme row is first created).
do $seed$
declare v_id uuid;
begin
`;
  progs.forEach((p, i) => {
    const extras = {};
    for (const k of ['video', 'obj', 'ba']) if (p[k] !== undefined) extras[k] = p[k];
    out += `
  -- ${p.n} ${p.t}
  insert into public.programmes (slug, position, name, short_label, context, caption, description, extras)
  values (${q(slugs[i])}, ${i}, ${q(p.t)}, ${q(p.s)}, ${q(p.m)}, ${q(p.cap)}, ${q(p.d)}, ${q(JSON.stringify(extras))}::jsonb)
  on conflict (slug) do nothing
  returning id into v_id;
  if v_id is not null then
    insert into public.programme_images (programme_id, position, src) values
${p.imgs.map((f, j) => `      (v_id, ${j}, ${q(f)})`).join(',\n')};
  end if;
  v_id := null;
`;
  });
  out += `
  -- Site information starts from the words on the original About page.
  update public.site_info set data = ${q(JSON.stringify(siteDefaults()))}::jsonb || data where id = 1;
end
$seed$;
`;
  writeFileSync(join(root, 'supabase/migrations/0002_seed_content.sql'), out);
  console.log('Wrote supabase/migrations/0002_seed_content.sql for', progs.length, 'programmes');
}

